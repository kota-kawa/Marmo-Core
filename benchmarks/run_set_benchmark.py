"""Set-selection benchmark: Set F1, dependency closure, and abstain/escalate.

Evaluates second-layer selectors (§15.3 案H) against gold resource sets on
the 4-kind corpus (benchmarks/corpus/set_corpus.json, generated by
generate_set_corpus.py). For every scenario the first layer retrieves a
candidate pool, each selector picks a set (or abstains / escalates), and the
result is scored against the gold set:

- Set Precision / Recall / F1 (mean over "selected" scenarios) and Set
  Exact Match
- Dependency Closure Rate: selected sets whose declared dependencies are
  all inside the set itself
- Conflict-Free Rate: selected sets with no conflicts_with pair inside
- Policy-Feasible Set Rate: selected sets whose required_permissions are
  covered by the scenario's granted permissions
- Status accuracy on abstain/escalate scenarios (§15.6: a selector must be
  able to *not* pick), plus Coverage over all scenarios

Selectors compared: ``topk`` (RuleBasedSetSelector, per-kind Top-K baseline),
``greedy`` (GreedyConstrainedSetSelector, 案H solver #1), ``beam``
(BeamSearchSetSelector, 案H solver #2), ``bnb`` (BranchAndBoundSetSelector,
案H solver #3 — exact Σu optimum, the yardstick for the approximate
solvers), and optionally ``llm``
(LLMSetSelector, 案C applied to the second layer — the strongest comparison
target; enable with ``--llm-selector``, needs OPENAI_API_KEY, replies cached
in benchmarks/cache/).

Policy ablation (§15.6): ``--policy-ablation`` runs every selector under the
five permission-enforcement conditions and reports where the safety check
should sit in the pipeline (Retrieval → Policy-feasible filtering → Set
Selection → Activation Gate):

- ``none``      — no permission enforcement anywhere
- ``gate-only`` — permission-blind retrieval and selection; the activation
                  gate (4.3, ``PolicyGateway``) checks the finished set and
                  escalates it when a member lacks permissions
- ``selector``  — the selector solves permission feasibility as a
                  constraint (the repo's default so far); no gate
- ``pushdown``  — retrieval hard-filters ungranted resources
                  (``require_permissions=True``) *and* the selector
                  enforces; no gate
- ``full``      — pushdown + selector + activation gate (defense in depth)

The ablation isolates the *permission* axis: the gate's PolicyContext
disables side-effect escalation, and the corpus has no trust levels the
default policy rejects, so the gate fires only on missing permissions.
The soft permission-fit component of the retrieval score is part of the
baseline ranking and stays identical across conditions.

First-layer routes: ``lexical`` (案A), ``hybrid-*`` (案B), ``graph-<base>``
(案E — ``CapabilityGraphRetriever`` expands the base retriever's seeds over
the declared capability/dependency graph before selection), and
``ce-<base>`` (§15.7 項目4 — ``CrossEncoderRerankRetriever`` re-scores the
base's pool with a local cross-encoder, which also moves the relevance
component the abstain gate thresholds).

Usage:
    python3 benchmarks/run_set_benchmark.py [--retriever lexical|hybrid-model|graph-hybrid-model|...]
                                            [--distractors DIR] [--llm-selector]
                                            [--policy-ablation]

``--distractors resources/skills`` mixes the ~1,000-skill corpus in as
retrieval noise to stress the first layer; gold ids stay in the set corpus.
"""

