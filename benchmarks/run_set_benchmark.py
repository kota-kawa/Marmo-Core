PER_KIND_LIMITS = {"memory": 1, "skill": 1, "tool": 1, "agent": 1}

# §15.6 ablation conditions: where does permission enforcement sit?
# filter = retrieval-time hard filter (require_permissions=True),
# enforce = the selector treats permissions as a constraint,
# gate = post-selection activation gate (PolicyGateway).
POLICY_CONDITIONS = {
    "none": {"filter": False, "enforce": False, "gate": False},
    "gate-only": {"filter": False, "enforce": False, "gate": True},
    "selector": {"filter": False, "enforce": True, "gate": False},
    "pushdown": {"filter": True, "enforce": True, "gate": False},
    "full": {"filter": True, "enforce": True, "gate": True},
}


def build_retriever(name: str, *, ce_weight: float = 1.0, ce_model: str | None = None):
    if name.startswith("graph-"):
        return CapabilityGraphRetriever(
            build_retriever(name.removeprefix("graph-"), ce_weight=ce_weight, ce_model=ce_model)
        )
    if name.startswith("ce-"):
        sys.path.insert(0, str(Path(__file__).parent))
        from run_benchmark import FastembedCrossEncoderProvider

        return CrossEncoderRerankRetriever(
            FastembedCrossEncoderProvider(ce_model),
            build_retriever(name.removeprefix("ce-"), ce_weight=ce_weight, ce_model=ce_model),
            weight=ce_weight,
        )
    if name == "lexical":
        return LexicalRetriever()
    if name == "hybrid-hash":
        return HybridRetriever(HashingEmbeddingProvider(dimensions=512), semantic_weight=0.5)
    if name == "hybrid-model":
        sys.path.insert(0, str(Path(__file__).parent))
        from run_benchmark import FastembedEmbeddingProvider

        return HybridRetriever(FastembedEmbeddingProvider(), semantic_weight=0.9)
    raise SystemExit(f"unknown retriever: {name}")


def evaluate_selected_set(selected_ids: set[str], resources_by_id: dict, gold: set[str], granted: set[str]) -> dict:
    true_positive = len(selected_ids & gold)
    precision = true_positive / len(selected_ids) if selected_ids else 0.0
    recall = true_positive / len(gold) if gold else 0.0
    f1 = (2 * precision * recall / (precision + recall)) if (precision + recall) else 0.0

    closure_ok = all(
        dependency in selected_ids
        for rid in selected_ids
        for dependency in resources_by_id[rid].metadata.dependencies
    )
    conflict_free = all(
        conflict not in selected_ids
        for rid in selected_ids
        for conflict in resources_by_id[rid].metadata.conflicts_with
    )
    feasible = all(
        set(resources_by_id[rid].metadata.required_permissions) <= granted for rid in selected_ids
    )
    return {
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "exact": selected_ids == gold,
        "closure_ok": closure_ok,
        "conflict_free": conflict_free,
        "feasible": feasible,
    }


def score_selection(selection, scenario: dict, resources_by_id: dict) -> tuple[dict, dict | None]:
    """Score one selector outcome against a scenario: (status record, set record or None)."""

    status_record = {
        "task": scenario["task"],
        "expected_status": scenario["expected_status"],
        "status": selection.status,
        "status_ok": selection.status == scenario["expected_status"],
    }
    set_record = None
    if scenario["expected_status"] == "selected":
        gold = set(scenario["gold_set"])
        granted = set(scenario["granted_permissions"])
        selected_ids = {result.resource.metadata.id for result in selection.results}
        set_record = evaluate_selected_set(selected_ids, resources_by_id, gold, granted)
        set_record["task"] = scenario["task"]
        set_record["selected"] = sorted(selected_ids)
        set_record["gold"] = sorted(gold)
    return status_record, set_record


def summarize(records: list[dict], statuses: list[dict], latencies: list[float]) -> dict:
    def rate(rows: list[dict], key: str) -> float:
        return round(sum(1 for row in rows if row[key]) / len(rows), 3) if rows else 0.0

    return {
        "set_precision": round(statistics.mean(r["precision"] for r in records), 3) if records else 0.0,
        "set_recall": round(statistics.mean(r["recall"] for r in records), 3) if records else 0.0,
        "set_f1": round(statistics.mean(r["f1"] for r in records), 3) if records else 0.0,
        "set_exact_match": rate(records, "exact"),
        "dependency_closure_rate": rate(records, "closure_ok"),
        "conflict_free_rate": rate(records, "conflict_free"),
        "policy_feasible_rate": rate(records, "feasible"),
        "status_accuracy": rate(statuses, "status_ok"),
        "abstain_escalate_accuracy": rate(
            [s for s in statuses if s["expected_status"] != "selected"], "status_ok"
        ),
        "coverage": round(
            sum(1 for s in statuses if s["status"] == "selected") / len(statuses), 3
        )
        if statuses
        else 0.0,
        "latency_ms_mean": round(statistics.mean(latencies), 3) if latencies else 0.0,
        "mistakes": [
            {"task": r["task"], "selected": r["selected"], "gold": r["gold"]}
            for r in records
            if not r["exact"]
        ]
        + [s for s in statuses if not s["status_ok"]],
    }


def apply_activation_gate(selection, granted: set[str]) -> tuple[SelectionResult, bool]:
    """Run the activation gate (4.3) over a selected set, permission axis only.

    A member missing permissions makes the whole set escalate — the secure
    default (the set cannot be activated as selected, and a human could
    grant the permissions), matching the selector-level escalate semantics
    so status accuracy compares insertion points, not vocabularies.
    Side-effect escalation is disabled to isolate the permission axis.
    """

    if selection.status != "selected" or not selection.results:
        return selection, False
    gateway = PolicyGateway()
    policy_context = PolicyContext(
        granted_permissions=tuple(sorted(granted)), escalate_side_effects=()
    )
    blocked = []
    for result in selection.results:
        decision = gateway.evaluate(result.resource, policy_context, gate="activation")
        if not decision.allowed:
            blocked.append(
                f"{decision.resource_id}: missing {', '.join(decision.missing_permissions) or decision.verdict}"
            )
    if blocked:
        gated = SelectionResult(
            (),
            "activation gate blocked the selected set: "
            + "; ".join(blocked[:3])
            + "; a human can grant the permissions and re-run",
            status="escalate",
        )
        return gated, True
    return selection, False


def run_policy_ablation(args, registry, resources_by_id, scenarios, retriever, selectors) -> dict:
    stats = {
        condition: {
            name: {"records": [], "statuses": [], "latencies": [], "gate_escalations": 0}
            for name in selectors
        }
        for condition in POLICY_CONDITIONS
    }
    recalls = {"unfiltered": [], "filtered": []}

    for scenario in scenarios:
        gold = set(scenario["gold_set"])
        granted = set(scenario["granted_permissions"])
        base_query = SearchQuery(
            task=scenario["task"],
            granted_permissions=tuple(sorted(granted)),
            top_k=args.pool,
        )
        pools = {
            False: retriever.search(registry, base_query),
            True: retriever.search(registry, replace(base_query, require_permissions=True)),
        }
        if gold:
            for label, filtered in (("unfiltered", False), ("filtered", True)):
                surfaced = {result.resource.metadata.id for result in pools[filtered]}
                recalls[label].append(len(gold & surfaced) / len(gold))
        contexts = {
            enforce: SelectionContext(
                task=scenario["task"],
                granted_permissions=tuple(sorted(granted)),
                per_kind_limits=PER_KIND_LIMITS,
                min_score=args.min_score,
                min_relevance=args.min_relevance,
                enforce_permissions=enforce,
            )
            for enforce in (False, True)
        }
        for condition, levers in POLICY_CONDITIONS.items():
            candidates = pools[levers["filter"]]
            context = contexts[levers["enforce"]]
            for name, selector in selectors.items():
                bucket = stats[condition][name]
                start = time.perf_counter()
                selection = selector.select(candidates, context=context)
                if levers["gate"]:
                    selection, gate_fired = apply_activation_gate(selection, granted)
                    bucket["gate_escalations"] += int(gate_fired)
                bucket["latencies"].append((time.perf_counter() - start) * 1000.0)
                status_record, set_record = score_selection(selection, scenario, resources_by_id)
                bucket["statuses"].append(status_record)
                if set_record is not None:
                    bucket["records"].append(set_record)

    report = {
        "mode": "policy-ablation",
        "retriever": args.retriever,
        "corpus_size": len(registry),
        "distractors": args.distractors,
        "scenarios": len(scenarios),
        "pool": args.pool,
        "min_score": args.min_score,
        "min_relevance": args.min_relevance,
        "retrieval_gold_recall": {
            label: round(statistics.mean(values), 3) if values else 0.0
            for label, values in recalls.items()
        },
        "conditions": {},
    }
    for condition in POLICY_CONDITIONS:
        report["conditions"][condition] = {"selectors": {}}
        for name in selectors:
            bucket = stats[condition][name]
            summary = summarize(bucket["records"], bucket["statuses"], bucket["latencies"])
            summary["gate_escalations"] = bucket["gate_escalations"]
            report["conditions"][condition]["selectors"][name] = summary
    return report


def main() -> None:
    load_local_dotenv()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus", default=str(Path(__file__).parent / "corpus" / "set_corpus.json"))
    parser.add_argument("--scenarios", default=str(Path(__file__).parent / "set_scenarios.json"))
    parser.add_argument("--distractors", default=None, help="extra resource dir mixed in as retrieval noise")
    parser.add_argument(
        "--retriever",
        default="lexical",
        choices=[
            "lexical",
            "hybrid-hash",
            "hybrid-model",
            "graph-lexical",
            "graph-hybrid-hash",
            "graph-hybrid-model",
            "ce-lexical",
            "ce-hybrid-model",
            "ce-graph-hybrid-model",
        ],
        help="graph-* wraps the base in CapabilityGraphRetriever (15.2 案E); ce-* wraps it in CrossEncoderRerankRetriever (15.7 項目4)",
    )
    parser.add_argument("--pool", type=int, default=50, help="candidate pool size handed to selectors")
    parser.add_argument("--min-score", type=float, default=0.45, help="selector abstain threshold on composite candidate scores")
    parser.add_argument("--min-relevance", type=float, default=0.55, help="greedy abstain threshold on the text-relevance component")
    parser.add_argument("--beam-width", type=int, default=5, help="beam width for beam search selector")
    parser.add_argument("--max-nodes", type=int, default=100_000, help="node budget for the branch-and-bound selector")
    parser.add_argument("--llm-selector", action="store_true", help="also run the LLM Set Selector (15.3 案C 第2層適用)")
    parser.add_argument("--llm-model", default=None, help="OpenAI-compatible chat model for --llm-selector (default: OPENAI_MODEL)")
    parser.add_argument("--ce-weight", type=float, default=1.0, help="blend weight of the cross-encoder score in relevance, for ce-* retrievers (15.7 項目4)")
    parser.add_argument("--ce-model", default=None, help="fastembed cross-encoder model for ce-* retrievers (default: BENCHMARK_CROSS_ENCODER_MODEL)")
    parser.add_argument("--policy-ablation", action="store_true", help="run the §15.6 policy ablation (none/gate-only/selector/pushdown/full)")
    parser.add_argument("--output", default=str(Path(__file__).parent / "results" / "set-selection.json"))
    args = parser.parse_args()

    paths = [args.corpus] + ([args.distractors] if args.distractors else [])
    registry = load_registry(paths)
    resources_by_id = {definition.metadata.id: definition for definition in registry.all()}
    scenarios = json.loads(Path(args.scenarios).read_text(encoding="utf-8"))["scenarios"]
    retriever = build_retriever(args.retriever, ce_weight=args.ce_weight, ce_model=args.ce_model)

    selectors = {
        "topk": RuleBasedSetSelector(default_limits=PER_KIND_LIMITS, min_score=args.min_score),
        "greedy": GreedyConstrainedSetSelector(),
        "beam": BeamSearchSetSelector(beam_width=args.beam_width),
        "bnb": BranchAndBoundSetSelector(max_nodes=args.max_nodes),
    }
    llm_cache = None
    llm_selector = None
    if args.llm_selector:
        sys.path.insert(0, str(Path(__file__).parent))
        from run_benchmark import _JsonFileCache

        llm = OpenAICompatibleLLMProvider(model=args.llm_model, max_tokens=512, temperature=0.0)
        args.llm_model = llm.model
        if not llm.api_key:
            raise SystemExit("--llm-selector needs OPENAI_API_KEY")
        llm_cache = _JsonFileCache(CACHE_DIR / f"set-selector-{args.llm_model}.json")
        llm_selector = LLMSetSelector(llm, cache=llm_cache)
        selectors["llm"] = llm_selector

    if args.policy_ablation:
        report = run_policy_ablation(args, registry, resources_by_id, scenarios, retriever, selectors)
        if llm_cache is not None:
            llm_cache.save()
        output_path = Path(args.output)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(json.dumps(stamp(report), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        recall = report["retrieval_gold_recall"]
        print(
            f"corpus: {len(registry)} resources | retriever: {args.retriever} | pool {args.pool} | "
            f"gold recall unfiltered {recall['unfiltered']:.0%} / filtered {recall['filtered']:.0%}"
        )
        for condition, payload in report["conditions"].items():
            print(f"  [{condition}]")
            for name, stats in payload["selectors"].items():
                print(
                    f"    {name}: SetF1 {stats['set_f1']:.3f} | exact {stats['set_exact_match']:.0%} | "
                    f"feasible {stats['policy_feasible_rate']:.0%} | status acc {stats['status_accuracy']:.0%} "
                    f"(abstain/escalate {stats['abstain_escalate_accuracy']:.0%}) | "
                    f"coverage {stats['coverage']:.0%} | gate esc {stats['gate_escalations']}"
                )
        print(f"report written to {output_path}")
        return

    per_selector: dict[str, list[dict]] = {name: [] for name in selectors}
    status_records: dict[str, list[dict]] = {name: [] for name in selectors}
    retrieval_gold_recall: list[float] = []
    latencies: dict[str, list[float]] = {name: [] for name in selectors}

    for scenario in scenarios:
        gold = set(scenario["gold_set"])
        granted = set(scenario["granted_permissions"])
        query = SearchQuery(
            task=scenario["task"],
            granted_permissions=tuple(sorted(granted)),
            top_k=args.pool,
        )
        candidates = retriever.search(registry, query)
        if gold:
            surfaced = {result.resource.metadata.id for result in candidates}
            retrieval_gold_recall.append(len(gold & surfaced) / len(gold))
        context = SelectionContext(
            task=scenario["task"],
            granted_permissions=tuple(sorted(granted)),
            per_kind_limits=PER_KIND_LIMITS,
            min_score=args.min_score,
            min_relevance=args.min_relevance,
        )
        for name, selector in selectors.items():
            start = time.perf_counter()
            selection = selector.select(candidates, context=context)
            latencies[name].append((time.perf_counter() - start) * 1000.0)
            status_record, set_record = score_selection(selection, scenario, resources_by_id)
            status_records[name].append(status_record)
            if set_record is not None:
                per_selector[name].append(set_record)

    if llm_cache is not None:
        llm_cache.save()

    report: dict = {
        "retriever": args.retriever,
        "llm_selector": (
            {"model": args.llm_model, "failures": llm_selector.failures}
            if llm_selector is not None
            else None
        ),
        "corpus_size": len(registry),
        "distractors": args.distractors,
        "scenarios": len(scenarios),
        "pool": args.pool,
        "min_score": args.min_score,
        "min_relevance": args.min_relevance,
        "retrieval_gold_recall": round(statistics.mean(retrieval_gold_recall), 3),
        "selectors": {},
    }
    for name in selectors:
        report["selectors"][name] = summarize(per_selector[name], status_records[name], latencies[name])

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(stamp(report), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(
        f"corpus: {len(registry)} resources | retriever: {args.retriever} | "
        f"pool {args.pool} | retrieval gold recall {report['retrieval_gold_recall']:.0%}"
    )
    for name, stats in report["selectors"].items():
        print(
            f"  {name}: SetF1 {stats['set_f1']:.3f} | exact {stats['set_exact_match']:.0%} | "
            f"closure {stats['dependency_closure_rate']:.0%} | conflict-free {stats['conflict_free_rate']:.0%} | "
            f"feasible {stats['policy_feasible_rate']:.0%} | status acc {stats['status_accuracy']:.0%} "
            f"(abstain/escalate {stats['abstain_escalate_accuracy']:.0%}) | {stats['latency_ms_mean']:.2f}ms"
        )
    print(f"report written to {output_path}")


if __name__ == "__main__":
    main()
